package org.omnione.did.common.datamodel.data.did;

import com.google.gson.annotations.SerializedName;
import org.omnione.did.common.datamodel.data.provider.Provider;
import org.omnione.did.common.datamodel.data.signature.Proof;

/**
 * Attested DID Document for P131 Wallet Registration Protocol.
 *
 * <p>Represents the data structure sent by a Wallet Provider to TAS when
 * registering a Wallet DID Document. The Provider attests (signs) this
 * structure to prove ownership and authenticity of the Wallet.</p>
 *
 * <p><b>Structure:</b></p>
 * <ul>
 *   <li>{@code walletId} - Wallet unique identifier (generated by Provider)</li>
 *   <li>{@code ownerDidDoc} - Multibase-encoded DID Document with key proofs</li>
 *   <li>{@code provider} - Wallet Provider DID and Certificate VC URL</li>
 *   <li>{@code nonce} - Random value for replay attack prevention</li>
 *   <li>{@code proof} - Provider's assertion signature over this structure</li>
 * </ul>
 */
public class AttestedDidDoc {

    @SerializedName("walletId")
    private String walletId;

    @SerializedName("ownerDidDoc")
    private String ownerDidDoc;

    @SerializedName("provider")
    private Provider provider;

    @SerializedName("nonce")
    private String nonce;

    @SerializedName("proof")
    private Proof proof;

    public AttestedDidDoc() {
    }

    public AttestedDidDoc(String walletId, String ownerDidDoc, Provider provider,
                          String nonce, Proof proof) {
        this.walletId = walletId;
        this.ownerDidDoc = ownerDidDoc;
        this.provider = provider;
        this.nonce = nonce;
        this.proof = proof;
    }

    public String getWalletId() {
        return walletId;
    }

    public void setWalletId(String walletId) {
        this.walletId = walletId;
    }

    public String getOwnerDidDoc() {
        return ownerDidDoc;
    }

    public void setOwnerDidDoc(String ownerDidDoc) {
        this.ownerDidDoc = ownerDidDoc;
    }

    public Provider getProvider() {
        return provider;
    }

    public void setProvider(Provider provider) {
        this.provider = provider;
    }

    public String getNonce() {
        return nonce;
    }

    public void setNonce(String nonce) {
        this.nonce = nonce;
    }

    public Proof getProof() {
        return proof;
    }

    public void setProof(Proof proof) {
        this.proof = proof;
    }

    public static Builder builder() {
        return new Builder();
    }

    public static class Builder {
        private String walletId;
        private String ownerDidDoc;
        private Provider provider;
        private String nonce;
        private Proof proof;

        public Builder walletId(String walletId) {
            this.walletId = walletId;
            return this;
        }

        public Builder ownerDidDoc(String ownerDidDoc) {
            this.ownerDidDoc = ownerDidDoc;
            return this;
        }

        public Builder provider(Provider provider) {
            this.provider = provider;
            return this;
        }

        public Builder nonce(String nonce) {
            this.nonce = nonce;
            return this;
        }

        public Builder proof(Proof proof) {
            this.proof = proof;
            return this;
        }

        public AttestedDidDoc build() {
            return new AttestedDidDoc(walletId, ownerDidDoc, provider, nonce, proof);
        }
    }

    @Override
    public String toString() {
        return "AttestedDidDoc{" +
                "walletId='" + walletId + '\'' +
                ", ownerDidDoc='" + ownerDidDoc + '\'' +
                ", provider=" + provider +
                ", nonce='" + nonce + '\'' +
                ", proof=" + proof +
                '}';
    }
}
